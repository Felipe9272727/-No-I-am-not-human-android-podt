#!/usr/bin/env python3
"""Generate C++ presentation metadata from retained static Unity manifests."""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'reconstruction/reverse-scenes/scene_render_manifest.json'
ENUM = ROOT / 'reconstruction/logic/cpp2il_cs/DiffableCs/Assembly-CSharp/_Code/Characters/EDialogEmotionState.cs'
EMOTIONS = ROOT / 'reconstruction/reverse-characters/emotion_registry.json'
CHARACTERS = ROOT / 'reconstruction/reverse-characters/character_configs.json'
OUT = ROOT / 'reconstruction/native-game/generated/presentation_provider.hpp'

def q(s): return json.dumps(str(s), ensure_ascii=True)
def num(v): return repr(float(v))+'f'
def vec2(v): return f'PresentationVec2{{{num(v[0])},{num(v[1])}}}'
def vec3(v): return f'PresentationVec3{{{num(v[0])},{num(v[1])},{num(v[2])}}}'
def asset(v):
    if not isinstance(v, dict) or 'path_id' not in v: return 'PresentationAsset{}'
    return f'PresentationAsset{{{int(v.get("file_id",0))},{int(v["path_id"])},true}}'

def sign(v):
    if not isinstance(v, dict): return 'PresentationSign{}'
    frames = ','.join(asset(x) for x in v.get('frames', []))
    primary = v if 'path_id' in v else v.get('sprite')
    return ('PresentationSign{'+asset(primary)+','+asset(v.get('white'))+','+asset(v.get('iris'))+
        ',std::vector<PresentationAsset>{'+frames+'},'+str(int(v.get('cycling_type_value',0)))+','+
        str(int(v.get('frames_per_second',0)))+','+num(v.get('distance_multiplier',0))+','+
        num(v.get('min_move_duration',0))+','+num(v.get('max_move_duration',0))+'}')

data=json.loads(MANIFEST.read_text())
emotion_data=json.loads(EMOTIONS.read_text())
character_data=json.loads(CHARACTERS.read_text())
records={c['character']:c for c in data['characters']}
character_types={(r['source_file'],int(r['path_id'])):int(r['character_type_value']) for r in character_data['records']}
room_instances={}
for inst in data['room_character_instances']:
    room_instances.setdefault(inst['character']['name'],inst)
if set(room_instances)!=set(records): raise ValueError('room manifest character instances do not match presentation characters')
animations={name:[] for name in records}
for e in emotion_data['records']:
    fields=e['fields']
    if e['class']=='CharacterAnimatedSpriteByEmotion':
        cycling, fps, frames=fields['cycling_type_value'], fields['frames_per_second'], fields['frame_sprites']
    else:
        cycling, fps, frames=2, 8, [fields['sprite']]
    animations.setdefault(e['character'],[]).append((e,cycling,fps,frames))
poses={}
for inst in data['room_character_instances']:
    name=inst['character']['name']
    dest=poses.setdefault(name,{})
    for p in inst['poses']:
        dest.setdefault(int(p['state_value']),p)
out=['// Generated by tools/reverse-scenes/generate_presentation_provider.py; do not edit.',
     '#pragma once','#include "ninah/presentation.hpp"','#include <utility>','#include <vector>',
     'namespace ninah::presentation_data {',
     'inline std::vector<CharacterPresentation> characters(){ std::vector<CharacterPresentation> out; out.reserve(%d);'%len(records)]
for name,c in records.items():
    instance=room_instances[name]
    initial=instance['initial_pose']
    out.append('{ CharacterPresentation c; c.name='+q(name)+'; c.source_file='+q(c['source']['file'])+
      '; c.source_path_id='+str(int(c['source']['path_id']))+'; c.character_type='+str(character_types[(c['source']['file'],int(c['source']['path_id']))])+
      '; c.room_enum='+str(int(instance['room_enum']))+'; c.scene_component_path_id='+str(int(instance['component']['path_id']))+
      '; c.game_object_path_id='+str(int(instance['game_object']['path_id']))+
      '; c.authored_active_self='+('true' if instance['game_object']['active_self'] else 'false')+
      '; c.authored_active_in_hierarchy='+('true' if instance['game_object']['active_in_hierarchy'] else 'false')+
      '; c.initial_pose_state='+str(int(initial['state_value']))+'; c.has_initial_pose=true'
      '; c.default_imposter='+('true' if c['is_imposter_default'] else 'false')+
      '; c.dialog_scale='+num(c['dialog_scale'])+'; c.room_scale='+num(c['room_scale'])+'; c.dialog_position='+vec2(c['dialog_position'])+';')
    for p in poses.get(name,{}).values():
        out.append('c.poses.push_back(PresentationPose{'+str(int(p['state_value']))+','+q(p['state'])+','+asset(p['sprite'])+','+
          vec2(p['position_shift'])+','+vec2(p['scale_shift'])+','+('true' if p['cannot_interact'] else 'false')+'});')
    for e in c['emotions']:
        out.append('c.emotions.push_back(PresentationEmotion{'+str(int(e['emotion_value']))+','+q(e['emotion_name'])+','+asset(e['fields'].get('sprite'))+'});')
    for e,cycling,fps,frames in animations.get(name,[]):
        out.append('c.emotion_animations.push_back(PresentationAnimation{'+str(int(e['emotion_value']))+','+q(e['emotion_name'])+','+
          str(int(cycling))+','+str(int(fps))+',std::vector<PresentationAsset>{'+','.join(asset(f) for f in frames)+'}});')
    for e in c['emotion_overrides']:
        out.append('c.emotion_overrides.push_back(PresentationOverride{'+str(int(e['emotion_value']))+','+vec3(e['position'])+','+vec3(e['scale'])+'});')
    ex=c['examination_assets']
    for imp in (False,True):
        suffix='imposter' if imp else 'human'; offset=6 if imp else 0
        vals=[ex.get('eye_sprite_'+suffix),ex.get('hands_sprite_'+suffix),ex.get('teeth_sprite_'+suffix),ex.get('photo_'+suffix),ex.get('armpit_'+suffix),ex.get('ear_'+suffix)]
        for i,v in enumerate(vals): out.append(f'c.signs[{offset+i}]={sign(v)};')
    out.append('out.push_back(std::move(c)); }')
out+=['return out; }','} // namespace ninah::presentation_data','']
enum_text=ENUM.read_text()
enum_pairs=re.findall(r'^\s*([A-Za-z_][A-Za-z_0-9]*)\s*=\s*(-?\d+)\s*,?\s*$', enum_text, re.M)
emotion_fn=['inline std::vector<std::pair<std::string,std::int32_t>> emotion_names(){ return {']
for n,v in enum_pairs: emotion_fn.append(' std::pair<std::string,std::int32_t>{'+q(n)+','+v+'},')
emotion_fn.append('}; }')
out=out[:-2]+emotion_fn+out[-2:]
OUT.parent.mkdir(parents=True,exist_ok=True); OUT.write_text('\n'.join(out))
print(f'generated {OUT.relative_to(ROOT)} ({len(records)} characters)')
