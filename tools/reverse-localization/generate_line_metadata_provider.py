#!/usr/bin/env python3
"""Generate the compact C++ lookup table from recovered LineMetadata JSON."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "reconstruction/reverse-localization/line_metadata.json"
OUTPUT = ROOT / "reconstruction/native-game/generated/production_line_metadata.hpp"
TAG_BITS = {
    "energy": 1 << 0,
    "day_dialog": 1 << 1,
    "get_item": 1 << 2,
    "give_item": 1 << 3,
    "gun": 1 << 4,
    "skip": 1 << 5,
    "rude": 1 << 6,
    "lastline": 1 << 7,
}


def main() -> None:
    report = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows = []
    for line_id, value in sorted(report["line_metadata"].items()):
        tags = {tag for metadata in value["metadata"] for tag in metadata["tags"]}
        unknown = tags - TAG_BITS.keys()
        if unknown:
            raise ValueError(f"unknown LineMetadata tags for {line_id}: {sorted(unknown)}")
        mask = 0
        for tag in tags:
            mask |= TAG_BITS[tag]
        rows.append((line_id, mask))
    if len(rows) != report["validation"]["graph_line_id_count"]:
        raise ValueError("exported line count does not match graph validation")
    if len({key for key, _ in rows}) != len(rows):
        raise ValueError("duplicate line IDs in metadata export")

    text = [
        "// Generated by tools/reverse-localization/generate_line_metadata_provider.py.",
        f"// Source bundle SHA-256: {report['source']['sha256']}",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "namespace ninah::generated {",
        "struct ProductionLineMetadata { std::string_view line_id; std::uint16_t tag_mask; };",
        "inline constexpr std::uint16_t kLineTagEnergy = 1u << 0;",
        "inline constexpr std::uint16_t kLineTagDayDialog = 1u << 1;",
        "inline constexpr std::uint16_t kLineTagGetItem = 1u << 2;",
        "inline constexpr std::uint16_t kLineTagGiveItem = 1u << 3;",
        "inline constexpr std::uint16_t kLineTagGun = 1u << 4;",
        "inline constexpr std::uint16_t kLineTagSkip = 1u << 5;",
        "inline constexpr std::uint16_t kLineTagRude = 1u << 6;",
        "inline constexpr std::uint16_t kLineTagLastLine = 1u << 7;",
        f"inline constexpr std::array<ProductionLineMetadata, {len(rows)}> kProductionLineMetadata{{{{",
    ]
    text.extend(f'    {{"{line_id}", {mask}}},' for line_id, mask in rows)
    text.extend(["}};", "} // namespace ninah::generated", ""])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(text), encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(rows)} exact line IDs")


if __name__ == "__main__":
    main()
