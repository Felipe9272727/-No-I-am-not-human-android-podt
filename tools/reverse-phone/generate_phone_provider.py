#!/usr/bin/env python3
"""Generate a phone provider from raw-asset-verified parsed evidence."""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "reconstruction/reverse-phone/phone_fixed_numbers.json"
FULL_SOURCE = ROOT / "reconstruction/reverse-phone/other_game_data.json"
RAW_SOURCE = ROOT / "reconstruction/reverse-phone/raw2715.bin"
OUTPUT = ROOT / "reconstruction/native-game/generated/production_phone.hpp"
EXPECTED_RAW_SHA256 = "f6c54b961c02a810320592e3ceb28c329e62a0134193ae26f47f0cd994d73a2f"


def main() -> None:
    evidence = json.loads(SOURCE.read_text(encoding="utf-8"))
    full = json.loads(FULL_SOURCE.read_text(encoding="utf-8"))
    metadata = evidence.get("source_object", {})
    source_metadata = full.get("source", {})
    if evidence.get("evidence_status") != "verified_from_raw_unity_asset_static_parse":
        raise SystemExit("phone evidence is not labelled as verified raw asset data")
    if metadata.get("path_id") != 2715 or source_metadata.get("path_id") != 2715:
        raise SystemExit("unexpected OtherGameData source path ID")
    actual = [
        (row.get("subscriber_value"), row.get("subscriber"), row.get("number"))
        for row in evidence.get("numbers", [])
    ]
    full_rows = [
        (row.get("subscriber_value"), row.get("subscriber"), row.get("number"))
        for row in full.get("values", {}).get("phone_numbers", [])
    ]
    if not actual or actual != full_rows:
        raise SystemExit("fixed-number subset does not match the fully parsed OtherGameData")
    raw_hash = hashlib.sha256(RAW_SOURCE.read_bytes()).hexdigest()
    if raw_hash != EXPECTED_RAW_SHA256:
        raise SystemExit("raw OtherGameData object SHA256 mismatch")
    if metadata.get("raw_sha256") != raw_hash or source_metadata.get("raw_sha256") != raw_hash:
        raise SystemExit("raw object hash metadata does not match raw2715.bin")
    if full.get("parsed_raw_bytes_end") != len(RAW_SOURCE.read_bytes()):
        raise SystemExit("OtherGameData parse did not consume the complete raw object")
    if full.get("unparsed_tail_bytes") != 0:
        raise SystemExit("OtherGameData contains an unparsed tail")
    for row in evidence["numbers"]:
        if row.get("value_evidence") != evidence["evidence_status"]:
            raise SystemExit("phone mapping evidence labels must match the verified status")

    rows = ",\n        ".join(
        f'{{static_cast<PhoneSubscriber>({value}), "{number}"}}'
        for value, name, number in actual
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by tools/reverse-phone/generate_phone_provider.py.\n"
        "// Values are decoded from the complete raw Unity MonoBehaviour object.\n"
        f"// Source object: OtherGameData path_id {metadata['path_id']}.\n"
        f"// sharedassets0.assets SHA256: {metadata['asset_sha256']}\n"
        f"// Raw object SHA256: {raw_hash}\n"
        "#pragma once\n"
        '#include "ninah/phone.hpp"\n'
        "namespace ninah::production {\n"
        "inline FixedPhoneNumbers fixed_phone_numbers() {\n"
        "    return FixedPhoneNumbers{\n        "
        + rows
        + "\n    };\n}\n"
        "} // namespace ninah::production\n",
        encoding="utf-8",
    )
    print(OUTPUT)


if __name__ == "__main__":
    main()
